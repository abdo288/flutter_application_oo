    echo ""
    echo "❌ فشل اختبار الأداء"
    exit 1
fi
echo "✅ نجح اختبار الأداء"
echo ""

# الاختبار الشامل
echo "========================================"
echo "[4/4] تشغيل جميع الاختبارات معاً"
