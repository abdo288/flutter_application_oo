#!/bin/bash
# =====================================================
# سكريبت تشغيل جميع اختبارات تبويب التقارير
# =====================================================

set -e

echo "========================================"
echo "بدء تشغيل اختبارات تبويب التقارير"
echo "========================================"
echo ""

# الانتقال إلى مجلد المشروع
cd "$(dirname "$0")/.."

# اختبار تدفق البكسل
echo ""
echo "========================================"
echo "[1/4] تشغيل اختبار تدفق البكسل"
echo "========================================"
flutter test test/reports_tab_pixel_flow_test.dart
