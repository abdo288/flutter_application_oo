    echo ""
    echo "❌ فشل اختبار التكامل"
    exit 1
fi
echo "✅ نجح اختبار التكامل"
echo ""

# اختبار الأداء
echo "========================================"
echo "[3/4] تشغيل اختبار الأداء"
echo "========================================"
